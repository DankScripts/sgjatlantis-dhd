    @Override
    public void render(BlockEntity blockEntity, float partialTick, PoseStack poseStack,
                       MultiBufferSource buffers, int packedLight, int packedOverlay) {
        if (!(blockEntity instanceof AbstractDHDEntity dhd)) {
            return;
        }
        if (!dhd.energyStorage.hasEnergy(1L)) {
            return;
        }

        ClientSymbols symbols = resolveClientSymbols(dhd);
        ClientPointOfOrigin pointOfOrigin = resolveClientPointOfOrigin(dhd);
        AbstractStargateEntity<?> gate = connectedGate(dhd);
        poseStack.pushPose();
        applyModelRotation(blockEntity.getBlockState(), poseStack);
        drawPoweredLightbar(poseStack, buffers);
        drawPoweredLightbarGlow(poseStack, buffers);

        for (Button button : OUTER_BUTTONS) {
            int symbol = button.symbol();
            drawButton(poseStack, buffers, dhd, symbols, button, symbol,
                    isSymbolEncoded(dhd, gate, symbol));
        }

        drawPointOfOrigin(poseStack, buffers, dhd, pointOfOrigin, POINT_OF_ORIGIN,
                isSymbolEncoded(dhd, gate, 0));
        drawButton(poseStack, buffers, dhd, symbols, SYMBOL_33, 33,
                isSymbolEncoded(dhd, gate, 33));
        drawButton(poseStack, buffers, dhd, symbols, SYMBOL_8, 8,
                isSymbolEncoded(dhd, gate, 8));

        if (dhd.isCenterButtonEngaged() || blockEntity.getLevel() != null
                && LanteaDhdTableLights.connected(blockEntity.getLevel().dimension().location(),
                        blockEntity.getBlockPos())) {
            drawGoldCrystal(poseStack, buffers, ENGAGE);
        }

        poseStack.popPose();
    }

    /**
     * A jumper engages symbols on the Stargate directly, so the table's own
     * address remains empty. Mirror the linked gate's synchronized encoded
     * symbols while it is dialing so the physical Atlantis table follows the
     * same sequence as the jumper console.
     */
    private static boolean isSymbolEncoded(AbstractDHDEntity dhd,
                                           AbstractStargateEntity<?> gate,
                                           int symbol) {
        if (dhd.isSymbolEncoded(symbol)) {
            return true;
        }
        if (dhd.getLevel() != null && LanteaDhdTableLights.encoded(
                dhd.getLevel().dimension().location(), dhd.getBlockPos(), symbol)) {
            return true;
        }
        if (gate == null || (!gate.isDialing() && gate.getChevronsEngaged() <= 0)) {
            return false;
        }
        try {
            return gate.getEncodedSymbols().containsSymbol(symbol);
        }
        catch (RuntimeException ignored) {
            return false;
        }
    }

