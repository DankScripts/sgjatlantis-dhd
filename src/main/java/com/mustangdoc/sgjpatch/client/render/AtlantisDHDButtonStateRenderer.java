    /** Fit the visible pixels, including their corners, inside the crystal's inset triangle. */
    private static double constellationScale(int width, int height, byte[] alpha, boolean up) {
        double scale = .54; // Up to 50% larger than the previous .36-width symbols.
        for (int y = 0; y < height; y++) for (int x = 0; x < width; x++) {
            if (alpha[y * width + x] == 0) continue;
            for (int dy = 0; dy <= 1; dy++) for (int dx = 0; dx <= 1; dx++) {
                double u = (x + dx) / (double) width - .5;
                double v = ((y + dy) / (double) height - .5) * (up ? 1 : -1);
                // Coordinates are relative to the centroid. Leave a 10% inset from the rim.
                double slope = Math.abs(u) + v / Math.sqrt(3);
                if (slope > 0) scale = Math.min(scale, .90 / (3 * slope));
                if (v < 0) scale = Math.min(scale, .90 * Math.sqrt(3) / (-6 * v));
            }
        }
        return scale;
    }

    private record SymbolMask(int width, int height, byte[] alpha, double upScale, double downScale) {
        private SymbolMask(int width, int height, byte[] alpha) {
            this(width, height, alpha, constellationScale(width, height, alpha, true),
                    constellationScale(width, height, alpha, false));
        }
    }

