    private static final Map<AbstractDHDEntity, NativeGlyphs> NATIVE_GLYPHS = new WeakHashMap<>();
    private record NativeGlyphs(long tick, double range, ResourceLocation symbols) {}

    private static ResourceLocation lanteaSymbols(AbstractDHDEntity dhd) {
        if (!(dhd.getLevel() instanceof ClientLevel level) || connectedGate(dhd) != null
                || !ModList.get().isLoaded("lantea")) return null;
        long tick = level.getGameTime();
        double range = dhd.getMaxConnectionDistance();
        var cached = NATIVE_GLYPHS.get(dhd);
        if (cached != null && cached.range() == range && tick >= cached.tick() && tick - cached.tick() < 20)
            return cached.symbols();
        var symbols = NativeGlyphLookup.find(level, dhd, range);
        NATIVE_GLYPHS.put(dhd, new NativeGlyphs(tick, range, symbols));
        return symbols;
    }

    private static final class NativeGlyphLookup {
        private static ResourceLocation find(ClientLevel level, AbstractDHDEntity dhd, double range) {
            var pos = dhd.getBlockPos();
            int radius = (int) Math.ceil(range);
            double bestDistance = range * range;
            StargateControllerBlockEntity best = null;
            for (int x = (pos.getX() - radius) >> 4; x <= ((pos.getX() + radius) >> 4); x++) {
                for (int z = (pos.getZ() - radius) >> 4; z <= ((pos.getZ() + radius) >> 4); z++) {
                    var chunk = level.getChunkSource().getChunkNow(x, z);
                    if (chunk == null) continue;
                    for (var candidate : chunk.getBlockEntities().values()) {
                        if (!(candidate instanceof StargateControllerBlockEntity gate)
                                || gate.isRemoved() || !gate.structureAssembled()) continue;
                        double distance = pos.distSqr(gate.getBlockPos());
                        if (distance > bestDistance || (best != null && distance == bestDistance)) continue;
                        best = gate;
                        bestDistance = distance;
                    }
                }
            }
            if (best == null) return null;
            return ResourceLocation.fromNamespaceAndPath("sgjourney", switch (best.kind().glyphSet().id()) {
                case "pg" -> "galaxy_pegasus";
                case "u" -> "universal";
                default -> "galaxy_milky_way";
            });
        }
    }
    private static ResourceLocation resolveSymbolsKey(AbstractDHDEntity dhd) {
        ResourceLocation nativeSymbols=lanteaSymbols(dhd);
        if(nativeSymbols!=null)return nativeSymbols;
        AbstractStargateEntity<?> gate = connectedGate(dhd);
        var variant = clientVariant(gate);
        if (variant != null && variant.symbols().permanentSymbols().isPresent())
            return variant.symbols().permanentSymbols().get().location();
        if (gate != null && gate.symbolInfo().symbols() != null) {
            return gate.symbolInfo().symbols().location();
        }
        return dhd.symbolInfo().symbols() == null
                ? null
                : dhd.symbolInfo().symbols().location();
    }

    private static ResourceLocation resolvePointOfOriginKey(AbstractDHDEntity dhd) {
        if (lanteaSymbols(dhd) != null) return ResourceLocation.fromNamespaceAndPath("sgjourney", "universal");
        AbstractStargateEntity<?> gate = connectedGate(dhd);
        var variant = clientVariant(gate);
        if (variant != null && variant.symbols().permanentPointOfOrigin().isPresent())
            return variant.symbols().permanentPointOfOrigin().get().location();
        if (gate != null && gate.symbolInfo().pointOfOrigin() != null) {
            return gate.symbolInfo().pointOfOrigin().location();
        }
        return dhd.symbolInfo().pointOfOrigin() == null
                ? null
                : dhd.symbolInfo().pointOfOrigin().location();
    }

    private static ResourceLocation symbolTextureFromResourceJson(ResourceLocation symbolsKey,
                                                                  int symbol) {
        if (symbolsKey == null || symbol <= 0) {
            return null;
        }
        boolean unique = net.povstalec.sgjourney.common.config.ClientStargateConfig.unique_symbols.get();
        ResourceLocation cacheKey = ResourceLocation.fromNamespaceAndPath(symbolsKey.getNamespace(),
                symbolsKey.getPath() + (unique ? "/unique" : "/shared"));
        List<ResourceLocation> textures = SYMBOL_TEXTURE_LISTS.computeIfAbsent(cacheKey,
                ignored -> loadSymbolTextureList(symbolsKey));
        return symbol <= textures.size() ? textures.get(symbol - 1) : null;
    }

    private static List<ResourceLocation> loadSymbolTextureList(ResourceLocation symbolsKey) {
        ResourceLocation json = ResourceLocation.fromNamespaceAndPath(symbolsKey.getNamespace(),
                "sgjourney/symbols/" + symbolsKey.getPath() + ".json");
        try {
            var resource = Minecraft.getInstance().getResourceManager().getResource(json);
            if (resource.isEmpty()) {
                return List.of();
            }
            try (var reader = new InputStreamReader(resource.get().open(), StandardCharsets.UTF_8)) {
                JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
                // The gate uses the shared symbol set when unique symbols are disabled.
                if (!net.povstalec.sgjourney.common.config.ClientStargateConfig.unique_symbols.get()
                        && root.has("symbol_set")) {
                    ResourceLocation set = ResourceLocation.tryParse(root.get("symbol_set").getAsString());
                    if (set != null) {
                        var setResource = Minecraft.getInstance().getResourceManager().getResource(
                                ResourceLocation.fromNamespaceAndPath(set.getNamespace(),
                                        "sgjourney/symbol_set/" + set.getPath() + ".json"));
                        if (setResource.isPresent()) {
                            try (var setReader = new InputStreamReader(setResource.get().open(), StandardCharsets.UTF_8)) {
                                root = JsonParser.parseReader(setReader).getAsJsonObject();
                            }
                        }
                    }
                }
                JsonArray entries = root.getAsJsonArray("textures");
                if (entries == null) {
                    return List.of();
                }
                List<ResourceLocation> textures = new ArrayList<>(entries.size());
                for (var entry : entries) {
                    ResourceLocation texture = ResourceLocation.tryParse(entry.getAsString());
                    if (texture != null) {
                        textures.add(texture);
                    }
                }
                return List.copyOf(textures);
            }
        }
        catch (Exception ignored) {
            return List.of();
        }
    }

